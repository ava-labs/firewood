#!/usr/bin/env bash

set -euo pipefail

readonly module_file="MODULE.bazel"
readonly begin_marker="# BEGIN GENERATED RUST TOOLCHAIN SHA256S"
readonly end_marker="# END GENERATED RUST TOOLCHAIN SHA256S"

usage() {
    cat <<'EOF'
Usage: scripts/update-bazel-rust-toolchain-shas.sh [--check]

Without arguments, download the configured Rust release manifest and regenerate
its Rules Rust archive checksums in MODULE.bazel. --check verifies that the
checked-in generated block targets the configured Rust version without making a
network request.
EOF
}

check=false
case "${1:-}" in
    "") ;;
    --check) check=true ;;
    -h|--help)
        usage
        exit 0
        ;;
    *)
        usage >&2
        exit 2
        ;;
esac

rust_version="$(
    awk '
        /^rust\.toolchain\(/ { in_toolchain = 1; next }
        in_toolchain && match($0, /versions = \["[^"]+"\]/) {
            version = substr($0, RSTART, RLENGTH)
            sub(/^versions = \["/, "", version)
            sub(/"\]$/, "", version)
            print version
            exit
        }
        in_toolchain && /^\)/ { in_toolchain = 0 }
    ' "$module_file"
)"

if [[ -z "$rust_version" ]]; then
    echo "error: could not find the Rules Rust toolchain version in $module_file" >&2
    exit 1
fi

if "$check"; then
    if ! grep -Fq "$begin_marker" "$module_file" || ! grep -Fq "$end_marker" "$module_file"; then
        echo "error: $module_file is missing generated Rust toolchain checksums; run $0" >&2
        exit 1
    fi

    if ! sed -n "/$begin_marker/,/$end_marker/p" "$module_file" | grep -Fq -- "-$rust_version-"; then
        echo "error: generated Rust toolchain checksums do not match $rust_version; run $0" >&2
        exit 1
    fi

    exit 0
fi

if ! command -v curl > /dev/null; then
    echo "error: curl is required to update Rust toolchain checksums" >&2
    exit 1
fi

temporary_dir="$(mktemp -d)"
cleanup() {
    rm -rf "$temporary_dir"
}
trap cleanup EXIT

manifest="$temporary_dir/channel-rust-$rust_version.toml"
generated="$temporary_dir/generated"
curl --fail --location --silent --show-error \
    "https://static.rust-lang.org/dist/channel-rust-$rust_version.toml" > "$manifest"

{
    echo "        $begin_marker"
    echo "        # Generated by scripts/update-bazel-rust-toolchain-shas.sh."

    for component in cargo clippy-preview llvm-tools-preview rust-std rustc; do
        for triple in aarch64-unknown-linux-gnu x86_64-unknown-linux-gnu; do
            archive="${component%-preview}-$rust_version-$triple.tar.xz"
            sha256="$(
                awk -v section="[pkg.$component.target.$triple]" '
                    $0 == section { found = 1; next }
                    found && /^\[/ { exit }
                    found && /^xz_hash = / {
                        gsub(/"/, "", $3)
                        print $3
                        exit
                    }
                ' "$manifest"
            )"

            if [[ -z "$sha256" ]]; then
                echo "error: $archive is missing from $manifest" >&2
                exit 1
            fi

            printf '        "%s": "%s",\n' "$archive" "$sha256"
        done
    done

    echo "        $end_marker"
} > "$generated"

awk -v begin_marker="$begin_marker" -v end_marker="$end_marker" -v generated="$generated" '
    BEGIN {
        while ((getline line < generated) > 0) {
            replacement = replacement line "\n"
        }
    }
    index($0, begin_marker) {
        printf "%s", replacement
        in_generated_block = 1
        found_begin = 1
        next
    }
    index($0, end_marker) {
        in_generated_block = 0
        found_end = 1
        next
    }
    !in_generated_block { print }
    END {
        if (!found_begin || !found_end) {
            exit 1
        }
    }
' "$module_file" > "$temporary_dir/MODULE.bazel"

if [[ ! -s "$temporary_dir/MODULE.bazel" ]]; then
    echo "error: $module_file is missing generated Rust toolchain checksum markers" >&2
    exit 1
fi

mv "$temporary_dir/MODULE.bazel" "$module_file"
